const SORTED = [...PHRASES].sort((a, b) => b[0].length - a[0].length);
const cache = new Map();

/** Condition text in English (phrase-by-phrase translation of the catalogue Italian). */
export function conditionEn(text) {
  if (!text) return text;
  if (cache.has(text)) return cache.get(text);
  let out = text;
  const marks = [];
  for (const [it, en] of SORTED) {
    if (!out.includes(it)) continue;
    // placeholders avoid translating the same words twice
    out = out.split(it).join(`\u0000${marks.length}\u0000`);
    marks.push(en);
  }
  out = out.replace(/\u0000(\d+)\u0000/g, (_, i) => marks[Number(i)]);
  cache.set(text, out);
  return out;
}

