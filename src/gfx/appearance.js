const t = createT(APPEARANCE_STRINGS);

export const appearanceTitle = () => t('title');
export const appearanceCaption = () => t('caption');

const cap = (s) => s.charAt(0).toUpperCase() + s.slice(1);

/** Didascalia dell'aspetto reale (una o due frasi). */
export function describeAppearance(z) {
  const a = APPEARANCE[z];
  if (!a) return '';
  const look = t(`look.${a.look}`);
  let text = t(`form.${a.form}`, { look, Look: cap(look) });
  if (a.form === 'unknown' && a.look === 'unknownMetal') text = `${text} ${cap(t('look.unknownMetal'))}.`;
  if (a.note) text += ` ${t(`note.${a.note}`)}`;
  return text;
}
